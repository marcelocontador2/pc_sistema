import shutil, datetime, ast

ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
back_path = r"pc_backend\main.py"
shutil.copy2(back_path, f"{back_path}.bak_config_{ts}")

c = open(back_path, encoding="utf-8-sig").read()

if "/api/configuracoes/entidade" in c:
    print("[AVISO] Rotas de configuracao ja existem no main.py.")
else:
    # Monta o bloco com indentacao correta (sem tabs, sem espacos sobrando no inicio)
    linhas_bloco = []
    linhas_bloco.append("")
    linhas_bloco.append("# ============================================================")
    linhas_bloco.append("# ROTAS DE CONFIGURACOES (CADASTRO DA ENTIDADE)")
    linhas_bloco.append("# ============================================================")
    linhas_bloco.append("")
    linhas_bloco.append("@app.get('/api/configuracoes/entidade')")
    linhas_bloco.append("async def obter_entidade():")
    linhas_bloco.append("    import sqlite3")
    linhas_bloco.append("    db_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'pc_storage', 'banco_dados.db')")
    linhas_bloco.append("    conn = sqlite3.connect(db_path)")
    linhas_bloco.append("    cursor = conn.cursor()")
    linhas_bloco.append("    cursor.execute('''CREATE TABLE IF NOT EXISTS configuracoes_entidade (")
    linhas_bloco.append("        id INTEGER PRIMARY KEY AUTOINCREMENT,")
    linhas_bloco.append("        razao_social TEXT, nome_fantasia TEXT, cnpj TEXT, endereco TEXT,")
    linhas_bloco.append("        email TEXT, telefone TEXT, contador_nome TEXT, contador_crc TEXT,")
    linhas_bloco.append("        contador_uf TEXT, contador_cpf TEXT, contador_email TEXT, data_atualizacao TEXT)''')")
    linhas_bloco.append("    conn.commit()")
    linhas_bloco.append("    cursor.execute('SELECT * FROM configuracoes_entidade ORDER BY id DESC LIMIT 1')")
    linhas_bloco.append("    row = cursor.fetchone()")
    linhas_bloco.append("    conn.close()")
    linhas_bloco.append("    if not row:")
    linhas_bloco.append("        return {'razao_social': '', 'nome_fantasia': '', 'cnpj': '', 'endereco': '', 'email': '', 'telefone': '', 'contador_nome': '', 'contador_crc': '', 'contador_uf': '', 'contador_cpf': '', 'contador_email': ''}")
    linhas_bloco.append("    return {'razao_social': row[1] or '', 'nome_fantasia': row[2] or '', 'cnpj': row[3] or '', 'endereco': row[4] or '', 'email': row[5] or '', 'telefone': row[6] or '', 'contador_nome': row[7] or '', 'contador_crc': row[8] or '', 'contador_uf': row[9] or '', 'contador_cpf': row[10] or '', 'contador_email': row[11] or ''}")
    linhas_bloco.append("")
    linhas_bloco.append("@app.post('/api/configuracoes/entidade')")
    linhas_bloco.append("async def salvar_entidade(request: Request):")
    linhas_bloco.append("    import sqlite3")
    linhas_bloco.append("    from datetime import datetime")
    linhas_bloco.append("    try:")
    linhas_bloco.append("        body = await request.json()")
    linhas_bloco.append("    except Exception:")
    linhas_bloco.append("        return {'ok': False, 'mensagem': 'Dados invalidos.'}")
    linhas_bloco.append("    db_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'pc_storage', 'banco_dados.db')")
    linhas_bloco.append("    conn = sqlite3.connect(db_path)")
    linhas_bloco.append("    cursor = conn.cursor()")
    linhas_bloco.append("    cursor.execute('''CREATE TABLE IF NOT EXISTS configuracoes_entidade (")
    linhas_bloco.append("        id INTEGER PRIMARY KEY AUTOINCREMENT,")
    linhas_bloco.append("        razao_social TEXT, nome_fantasia TEXT, cnpj TEXT, endereco TEXT,")
    linhas_bloco.append("        email TEXT, telefone TEXT, contador_nome TEXT, contador_crc TEXT,")
    linhas_bloco.append("        contador_uf TEXT, contador_cpf TEXT, contador_email TEXT, data_atualizacao TEXT)''')")
    linhas_bloco.append("    data_agora = datetime.now().strftime('%Y-%m-%d %H:%M:%S')")
    linhas_bloco.append("    cursor.execute('DELETE FROM configuracoes_entidade')")
    linhas_bloco.append("    cursor.execute('''INSERT INTO configuracoes_entidade")
    linhas_bloco.append("        (razao_social, nome_fantasia, cnpj, endereco, email, telefone, contador_nome, contador_crc, contador_uf, contador_cpf, contador_email, data_atualizacao)")
    linhas_bloco.append("        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)''', (")
    linhas_bloco.append("        body.get('razao_social', ''),")
    linhas_bloco.append("        body.get('nome_fantasia', ''),")
    linhas_bloco.append("        body.get('cnpj', ''),")
    linhas_bloco.append("        body.get('endereco', ''),")
    linhas_bloco.append("        body.get('email', ''),")
    linhas_bloco.append("        body.get('telefone', ''),")
    linhas_bloco.append("        body.get('contador_nome', ''),")
    linhas_bloco.append("        body.get('contador_crc', ''),")
    linhas_bloco.append("        body.get('contador_uf', ''),")
    linhas_bloco.append("        body.get('contador_cpf', ''),")
    linhas_bloco.append("        body.get('contador_email', ''),")
    linhas_bloco.append("        data_agora))")
    linhas_bloco.append("    conn.commit()")
    linhas_bloco.append("    conn.close()")
    linhas_bloco.append("    return {'ok': True, 'mensagem': 'Configuracoes salvas com sucesso!'}")
    linhas_bloco.append("")
    linhas_bloco.append("@app.get('/configuracoes')")
    linhas_bloco.append("async def serve_configuracoes():")
    linhas_bloco.append("    from fastapi.responses import FileResponse")
    linhas_bloco.append("    caminho = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'pc_frontend', 'configuracoes.html')")
    linhas_bloco.append("    return FileResponse(caminho, headers={'Cache-Control': 'no-store, no-cache, must-revalidate'})")
    linhas_bloco.append("")
    
    bloco = "\n".join(linhas_bloco)
    
    # Insere no final do arquivo (apos a ultima linha)
    c = c + "\n" + bloco
    open(back_path, "w", encoding="utf-8").write(c)
    
    try:
        ast.parse(open(back_path, encoding="utf-8").read())
        print("[OK] Rotas de configuracao inseridas no main.py e sintaxe validada.")
    except SyntaxError as e:
        print(f"[ERRO] Sintaxe quebrada: {e}")
        shutil.copy2(f"{back_path}.bak_config_{ts}", back_path)
        print("[OK] Backup restaurado.")
